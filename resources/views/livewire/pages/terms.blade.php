            <h3 class="font-display font-bold text-base text-[#2d0012] pt-2">1. Personal Information Collected</h3>
            <p>
                For official registration in the National Service Training Program, the system collects student identification numbers, full names, academic programs, gender, dates of birth, city and provincial addresses, contact phone numbers, and university email addresses.
            </p>

            <h3 class="font-display font-bold text-base text-[#2d0012] pt-2">2. Purpose of Collection</h3>
            <p>
                Student personal information is collected and processed solely for:
            </p>
            <ul class="list-disc pl-5 space-y-1">
                <li>Official enrollment records and academic grade tracking under RA 9163.</li>
                <li>Transmittal of masterlists to the Commission on Higher Education (CHED) and the Department of National Defense (DND) for the assignment of national serial numbers.</li>
                <li>Registration into the National Service Reserve Corps (NSRC) or the Citizen Armed Force (Reserve Force).</li>
                <li>Emergency contact during community outreach immersion and military conditioning training.</li>
            </ul>

            <h3 class="font-display font-bold text-base text-[#2d0012] pt-2">3. Storage & Security Measures</h3>
            <p>
                The EVSU NSTP Management System enforces strict role-based access control, cryptographic password hashing, auditable operation logs, and secure database isolation hosted on institutional servers. Unauthorized access, alteration, or disclosure is punishable under Philippine law.
            </p>

            <h3 class="font-display font-bold text-base text-[#2d0012] pt-2">4. Rights of Data Subjects</h3>
            <p>
                Under the Data Privacy Act, registered trainees retain the right to be informed, access their personal records, dispute inaccuracies, and request rectification of erroneously transcribed personal data through the official EVSU Data Protection Officer (DPO).
            </p>
